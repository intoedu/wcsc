(function numberServices() {
  var n = 0;
  categories.forEach(function (c) {
    services.forEach(function (s) {
      if (s.category !== c.id) return;
      n += 1;
      s.no = String(n).padStart(2, '0');
    });
  });
  // 갈래가 없는 항목이 생기더라도 번호는 받게 둡니다.
  services.forEach(function (s) {
    if (!s.no) { n += 1; s.no = String(n).padStart(2, '0'); }
  });
}());

